/// The code page of an RTF `\fcharsetN` (null = Unicode-only / symbol /
/// DBCS: the reader then relies on `\uN`).
int? codepageOfCharset(int charset) => switch (charset) {
  0 => 1252,
  1 => null, // DEFAULT_CHARSET: the document's \ansicpg
  2 => null, // SYMBOL
  161 => 1253,
  162 => 1254,
  186 => 1257,
  204 => 1251,
  238 => 1250,
  _ => null,
};

/// Whether [codepage] has a table here.
bool hasCodepage(int codepage) => _upperHalves.containsKey(codepage);

/// The character byte [b] stands for in [codepage] (1252 when unknown).
String decodeAnsiByte(int b, int codepage) {
  if (b < 0x80) return String.fromCharCode(b);
  final t = _upperHalves[codepage] ?? _upperHalves[1252]!;
  return t[b - 0x80];
}
